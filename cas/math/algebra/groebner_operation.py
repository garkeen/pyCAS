E = TypeVar("E")

_REPRESENTATION_MISSING = frozenset(
    {"multivariate_polynomial_representation"}
)
_FIELD_MISSING = frozenset({"coefficient_field"})
_RESTRICTED_REGION_MISSING = frozenset({"restricted_region"})

_CAPABILITY_REQUIREMENTS: CapabilityRequirements = frozenset(
    {Capability.FIELD, Capability.POLYNOMIAL_RING}
)


@dataclass(frozen=True, slots=True)
class GroebnerOperation(Generic[E]):
    """Registered problem and proposal builder for a reduced basis.

    The pre-assembled ring, bridge and request are the single authority for
    the coefficient structure, generator order and monomial order.  The
    operation fixes the result language to a finite `Set` and the coverage to
    `COMPLETE_SET`: a reduced basis is the complete answer to this problem, not
    a partial list of generators.
    """

    signature: LanguageSignature
    frames: FrameStore
    vocabulary: GroebnerVocabulary
    checker_id: str
    ring: PolynomialRing[E]
    bridge: MultivariatePolynomialBridge[E]
    request: AlgebraRequest
    budget: int = 1 << 16
    id: str = "groebner_basis"
    version: str = "1"
    problem_kind: str = "groebner_basis"
    specification_kind: str = "HasGroebnerBasis"
    checker_bindings: tuple[CheckerBinding, ...] = ()

    def __post_init__(self) -> None:
        if self.ring is not self.bridge.ring:
            raise ValueError(
                "the Groebner operation ring is not the bridge's ring"
            )
        if self.vocabulary.order is not self.ring.monomial_order:
            raise ValueError(
                "the vocabulary order is not the ring's monomial order"
            )
        if self.request.roles.target is not None:
            raise ValueError(
                "a Groebner operation needs a generator-mode request"
            )
        if self.request.roles.variables != self.ring.generators:
            raise ValueError(
                "the request generator roles are not the ring's generators "
                "in ring order"
            )
        if isinstance(self.budget, bool) or not isinstance(self.budget, int):
            raise TypeError(
                "the Groebner search budget must be an int (bool is not "
                "accepted)"
            )
        if self.budget < 0:
            raise ValueError(
                "the Groebner search budget must be nonnegative"
            )
        object.__setattr__(
            self,
            "checker_bindings",
            (
                CheckerBinding(
                    self.specification_kind,
                    self.problem_kind,
                    self.checker_id,
                    candidate_role=CandidateRole.SET,
                ),
            ),
        )

    @property
    def input_schema(self) -> InputSchema:
        return InputSchema("groebner_basis/generators", self._admit_input)

    @property
    def parameter_schema(self) -> ParameterSchema[None]:
        return EMPTY_PARAMETER_SCHEMA

    @property
    def result_schema(self) -> ResultSchema:
        return ResultSchema(
            frozenset({ResultLanguage.SET}),
            ResultShape.SET,
        )

    @property
    def capability_requirements(self) -> frozenset[Capability]:
        return _CAPABILITY_REQUIREMENTS

    def _admit_input(self, request: OperationRequest) -> InputAdmission:
        """Admit one generator tuple through the single fragment rule.

        Admission and proposal share this rule: the target shape, the absent
        restricted region and the coefficient field are checked here, and
        every term must convert through the multivariate bridge.  A refusal
        names the missing capability instead of guessing a basis.
        """
        if len(request.inputs) < 1:
            return InvalidRequest(
                ("Groebner basis needs at least one polynomial generator",)
            )
        if request.target is not None:
            return InvalidRequest(
                (
                    "Groebner basis binds the ring's ordered generator tuple; "
                    "it has no target variable",
                )
            )
        if request.region is not None:
            return Refused(
                Reason.FRAGMENT,
                "groebner_basis has no restricted-region form",
                FragmentReport(missing=_RESTRICTED_REGION_MISSING),
            )
        if not isinstance(self.ring.coefficients, Field):
            return Refused(
                Reason.FRAGMENT,
                "a Groebner basis needs a field of coefficients",
                FragmentReport(missing=_FIELD_MISSING),
            )
        typed_inputs = elaborate.typed_inputs(
            request.inputs,
            self.frames,
            request.frame,
            self.signature,
        )
        if not isinstance(typed_inputs, tuple):
            return InvalidRequest((typed_inputs.detail,))
        for typed in typed_inputs:
            outcome = self.bridge.to_view(typed, self.request)
            if isinstance(outcome, ViewRefused):
                missing = outcome.missing
                if outcome.reason is Reason.FRAGMENT:
                    missing = missing | _REPRESENTATION_MISSING
                return Refused(
                    outcome.reason,
                    outcome.detail,
                    FragmentReport(
                        missing=missing,
                        conditions=outcome.conditions,
                    ),
                )
        return Admitted()

    def build_problem(self, request: OperationRequest) -> ProblemOutcome:
        parameters = self.parameter_schema.parse(request.parameters)
        if isinstance(parameters, InvalidRequest):
            return invalid_problem(parameters)
        if len(request.inputs) < 1:
            return ProblemInvalid(
                "Groebner basis needs at least one polynomial generator"
            )
        if request.target is not None:
            return ProblemInvalid(
                "Groebner basis binds the ring's ordered generator tuple; it "
                "has no target variable"
            )
        typed_inputs = elaborate.typed_inputs(
            request.inputs,
            self.frames,
            request.frame,
            self.signature,
        )
        if not isinstance(typed_inputs, tuple):
            return ProblemInvalid(typed_inputs.detail)
        result_language = self.result_schema.single_language()
        # The request region is fixed into the problem so a blocked task shows
        # exactly what the user asked for.  Admission refuses it below, before
        # any claim is fixed as supported.
        problem = ProblemSpec(
            operation=self.problem_kind,
            inputs=typed_inputs,
            roles=self.request.roles,
            region=request.region,
            result_language=result_language,
            coverage=Coverage.COMPLETE_SET,
            interpretation_requirement=(
                self.request.interpretation_requirement
            ),
            domain_requirement=DomainRequirement(
                coefficient=self.request.coefficient_domain,
                values=self.request.value_domain,
            ),
        )
        admission = self.input_schema.admit(request)
        if isinstance(admission, Refused):
            return unsupported_problem(admission, problem)
        if isinstance(admission, InvalidRequest):
            return invalid_problem(admission)
        fit = fit_request(
            request,
            result_language=result_language,
            parameter_mode=self.request.parameter_mode,
            coverages=frozenset({Coverage.COMPLETE_SET}),
        )
        if isinstance(fit, RequestMismatch):
            return unsupported_request(fit, problem)
        return ProblemBuilt(problem, algebra=self.request)

    def _render(
        self,
        view: AlgebraView[Polynomial[E]],
        value: Polynomial[E],
    ) -> T.Term | RenderRefused:
        rendered = self.bridge.render(view, value)
        if isinstance(rendered, RenderRefused):
            return rendered
        return rendered.term

    def propose(
        self,
        execution: ExecutionRequest,
    ) -> ProposalOutcome:
        request = execution.request
        problem = execution.problem
        parameters = self.parameter_schema.parse(request.parameters)
        if isinstance(parameters, InvalidRequest):
            return ProposalInvalid("; ".join(parameters.issues))
        if execution.algebra is not self.request:
            return ProposalInvalid(
                "the execution does not use this operation's algebra request"
            )
        if problem.operation != self.problem_kind:
            return ProposalInvalid(
                "the execution problem is not a Groebner basis problem"
            )
        typed_inputs: dict[T.Term, Ty.TypedExpr] = {}
        for item in problem.inputs:
            typed_inputs.setdefault(item.term, item)
        generator_set = set_term(
            self.signature,
            tuple(item.term for item in problem.inputs),
        )
        generator_terms = set_members(generator_set, self.signature)
        if generator_terms is None:
            return ProposalInvalid(
                "the generator set is not a finite-set term"
            )
        values: list[Polynomial[E]] = []
        view: AlgebraView[Polynomial[E]] | None = None
        for term in generator_terms:
            typed = typed_inputs.get(term)
            if typed is None:
                return ProposalInvalid(
                    "the canonical generator set does not match the problem "
                    "inputs"
                )
            outcome = self.bridge.to_view(typed, self.request)
            if isinstance(outcome, ViewRefused):
                return ProposalUnsupported(
                    outcome.reason,
                    outcome.detail,
                    missing=outcome.missing,
                    conditions=outcome.conditions,
                )
            if outcome.view.source.term != term:
                return ProposalInvalid(
                    "the elaborated generator does not match the claim"
                )
            values.append(outcome.view.value)
            if view is None:
                view = outcome.view
        if view is None:
            return ProposalInvalid(
                "a Groebner basis needs at least one generator"
            )
        try:
            record = buchberger(
                self.ring, values, budget=self.budget
            )
        except BuchbergerBudgetError as error:
            return ProposalUnsupported(
                Reason.BUDGET,
                error.detail,
                missing=error.missing,
            )
        except GroebnerFragmentError as error:
            return ProposalUnsupported(
                Reason.FRAGMENT,
                error.detail,
                missing=error.missing,
            )
        rendered_basis: list[T.Term] = []
        basis_positions: dict[T.Term, int] = {}
        for index, element in enumerate(record.basis):
            rendered = self._render(view, element)
            if isinstance(rendered, RenderRefused):
                return ProposalUnsupported(
                    rendered.reason,
                    rendered.detail,
                    missing=rendered.missing,
                )
            rendered_basis.append(rendered)
            basis_positions[rendered] = index
        basis_set = set_term(self.signature, tuple(rendered_basis))
        basis_terms = set_members(basis_set, self.signature)
        if basis_terms is None:
            return ProposalInvalid(
                "the basis set is not a finite-set term"
            )
        if len(record.original_generators) != len(generator_terms):
            return ProposalInvalid(
                "the searched generator tuple does not match the canonical "
                "generator set"
            )
        rows: list[tuple[T.Term, ...]] = []
        for term in basis_terms:
            position = basis_positions.get(term)
            if position is None:
                return ProposalInvalid(
                    "the canonical basis set does not match the searched "
                    "basis"
                )
            row: list[T.Term] = []
            for cofactor in record.cofactors[position]:
                rendered = self._render(view, cofactor)
                if isinstance(rendered, RenderRefused):
                    return ProposalUnsupported(
                        rendered.reason,
                        rendered.detail,
                        missing=rendered.missing,
                    )
                row.append(rendered)
            rows.append(tuple(row))
        issued = elaborate.proposition(
            has_groebner_basis(
                self.vocabulary,
                generator_set,
                basis_set,
                self.vocabulary.order_term(),
            ),
            self.frames,
            request.frame,
            self.signature,
        )
        if not isinstance(issued, Pr.Proposition):
            return ProposalInvalid(
                "the Groebner-basis specification is not a proposition"
            )
        return Proposed(
            MathematicalProposal(
                result=basis_set,
                specifications=(issued,),
                specification_kind=self.specification_kind,
                certificate=GroebnerCertificate(tuple(rows)),
                answer_coverage=Coverage.COMPLETE_SET,
                trace=(
                    f"pairs={record.statistics.pairs}",
                    f"reductions={record.statistics.reductions}",
                ),
            )
        )


__all__ = ["GroebnerOperation"]
