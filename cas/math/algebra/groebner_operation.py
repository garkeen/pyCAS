"""Registered verification-first reduced Groebner basis over one fixed order.

The operation computes the unique reduced Groebner basis of the ideal
generated by a finite set of multivariate polynomials over a field.  Its
specification is `HasGroebnerBasis(G, B, O)` and its result language is a
finite set of polynomial terms.  It is a statement about an ideal
presentation: it does not assert real or complex solutions, rational points,
a dimension, or any elimination result.

Fragment
--------

This vertical slice is the fixed default assembly ``Q[x, y]`` under LEX.  The
coefficient structure must be a field (positive characteristic is allowed:
Buchberger's criterion does not need ordered or characteristic-zero
coefficients), every input must convert through the multivariate polynomial
bridge, and the request must bind the ring's ordered generator tuple with no
target and no parameter ring.  A restricted-region request, an explicit target,
a non-field coefficient structure or an unconvertible term is refused as a
structured fragment gap.  Multiple monomial orders, parameterized multivariate
rings, G1 elimination/ideal intersection/quotient algebras and G2 solution-set
semantics are outside this slice: the fixed order is the ring's order and no
order parameter is accepted.

Search and trust boundary
-------------------------

The search side is ``cas.algebra.groebner.buchberger``; this module is the
registered problem/proposal builder and never publishes a judgment.  The
independent checker ``cas.math.algebra.groebner_checker`` re-derives the
reduced-basis facts, the Buchberger criterion and the cofactor identities from
the proposal, and this module does not import it.  The certificate records the
cofactor matrix of every claimed basis element in terms of the canonical
generator order; the checker validates the shape and every identity.

Budget
------

``budget`` counts critical pairs and leading-term reductions in the search.
Exhaustion raises ``BuchbergerBudgetError`` and is reported as
``ProposalUnsupported(BUDGET)``; no partial basis is ever proposed.  A budget
never changes the mathematical truth of a completed answer.

References
----------

B. Buchberger, doctoral thesis (1965) and *Aequationes Mathematicae* 4 (1970),
374-383, for the algorithm and the S-polynomial criterion.  D. Cox, J. Little
and D. O'Shea, *Ideals, Varieties, and Algorithms*, 4th ed., Chapter 2, for the
division algorithm, the reduced basis and the uniqueness of the reduced
Groebner basis.  Reference implementations: FriCAS ``src/algebra/gb.spad`` and
``src/algebra/gbintern.spad``; Maxima ``share/algebra/grob1.lisp``.
"""

