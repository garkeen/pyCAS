"""The `HasGroebnerBasis(G, B, O)` specification over a fixed monomial order.

The predicate states that ``B`` is the unique reduced Groebner basis of the
ideal generated by the finite set ``G`` in the request's polynomial ring under
the order named by ``O``.  It is a statement about an ideal presentation, not a
solution set: it does not assert real or complex solutions, rational points, a
dimension, or any elimination result.  ``G`` and ``B`` are finite sets of
polynomial expressions; ``O`` is quoted syntax naming a monomial order, so it is
data rather than a mathematical operand.

The certificate carries the cofactor matrix expressing every claimed basis
element as a polynomial combination of the original generators.  It is not a
trusted result: the independent checker recomputes the reduction identities and
the Buchberger criterion from the candidate and the certificate.

This module only publishes the language-level claim shape.  The G0 search and
its sealed record live in ``cas.algebra.groebner``; the independent checker is
``cas.math.algebra.groebner_checker``.  Neither the registered operation nor the
bootstrap wiring, the workflow or the REPL is part of this slice, and none of
this is G1/G2 solution-set semantics.
"""

from __future__ import annotations

from dataclasses import dataclass

from cas.algebra.polynomial import MonomialOrder
from cas.foundation.ids import SymbolId
from cas.language import sorts as S
from cas.language.signatures import OperatorSignature
from cas.syntax import term as T


@dataclass(frozen=True, slots=True)
class GroebnerVocabulary:
    """The predicate and order symbols one world uses for Groebner claims.

    ``member_sort`` is the scalar sort of every polynomial expression in the
    generator and basis sets.  ``order`` is the fixed monomial order this
    vocabulary names; ``order_symbol`` is the symbol whose name carries
    ``order.value`` inside the quoted third argument.
    """

    symbol: SymbolId
    name: str
    order_symbol: SymbolId
    order: MonomialOrder
    member_sort: S.Sort = S.REAL

    def __post_init__(self) -> None:
        if not isinstance(self.name, str) or not self.name:
            raise ValueError("a Groebner predicate needs a name")
        if not isinstance(self.order, MonomialOrder):
            raise TypeError("a Groebner predicate needs a MonomialOrder")
        if not isinstance(self.member_sort, S.Sort):
            raise TypeError("a Groebner member sort must be a Sort")
        if not S.is_scalar(self.member_sort):
            raise ValueError("a Groebner member sort must be scalar")

    @property
    def signature(self) -> OperatorSignature:
        """`(generators, basis, quoted-order) -> proposition`."""
        member = S.SetSort(self.member_sort)
        return OperatorSignature(
            (member, member, S.SYNTAX),
            S.PROPOSITION,
        )

    def order_term(self) -> T.Term:
        """The canonical quoted order term for this vocabulary."""
        return T.quote(T.symbol(self.order_symbol, self.order.value))


@dataclass(frozen=True, slots=True)
class GroebnerClaim:
    """The three arguments of one `HasGroebnerBasis` application."""

    generators: T.Term
    basis: T.Term
    order: T.Term

    def __post_init__(self) -> None:
        if not all(
            isinstance(item, T.Term)
            for item in (self.generators, self.basis, self.order)
        ):
            raise TypeError("a Groebner claim needs term arguments")


@dataclass(frozen=True, slots=True)
class GroebnerCertificate:
    """The cofactor matrix behind one reduced-basis claim.

    ``cofactors[i][j]`` is the polynomial multiplier of generator ``j`` in the
    representation of basis element ``i``.  Rows align with the claim's basis
    set and columns with its generator set in the canonical member order the
    checker reads.  The matrix is empty when the basis is empty; the checker
    validates its shape against the claim before evaluating any identity.
    """

    cofactors: tuple[tuple[T.Term, ...], ...]

    def __post_init__(self) -> None:
        rows = tuple(tuple(row) for row in self.cofactors)
        if any(
            not isinstance(item, T.Term) for row in rows for item in row
        ):
            raise TypeError("a Groebner certificate carries term cofactors")
        object.__setattr__(self, "cofactors", rows)


def has_groebner_basis(
    vocabulary: GroebnerVocabulary,
    generators: T.Term,
    basis: T.Term,
    order: T.Term,
) -> T.Term:
    """Build a reduced-Groebner-basis specification term."""
    if not all(
        isinstance(item, T.Term)
        for item in (generators, basis, order)
    ):
        raise TypeError("a Groebner specification needs term arguments")
    return T.app(
        T.symbol(vocabulary.symbol, vocabulary.name),
        generators,
        basis,
        order,
    )


def parse_groebner(
    vocabulary: GroebnerVocabulary,
    term: T.Term,
) -> GroebnerClaim | None:
    """Recognize this predicate's application, or return None."""
    if not isinstance(term, T.Apply) or not isinstance(
        term.operator, T.SymbolRef
    ):
        return None
    if term.operator.symbol_id != vocabulary.symbol:
        return None
    if len(term.arguments) != 3:
        return None
    generators, basis, order = term.arguments
    return GroebnerClaim(generators, basis, order)


__all__ = [
    "GroebnerCertificate",
    "GroebnerClaim",
    "GroebnerVocabulary",
    "has_groebner_basis",
    "parse_groebner",
]
