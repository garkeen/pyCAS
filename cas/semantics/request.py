"""An explicit algebra request: coefficient structure, roles and interpretation.

A symbol's role is a property of the request, not of the symbol. The same symbol
may be a parameter in one request and the target in another; no request mutates a
global role registry. The coefficient structure and the parameter ring are
separate parents, so polynomial coefficients are not confused with the target
generators.

The request is the algebra view, not the problem statement.  It shares the
language-owned `VariableRoles` value with the problem it resolves; an operation
selects one pre-assembled request and derives its `ProblemSpec` from it.

The differential payload is request-local: it names the derivation this request
uses on its coefficient/target structure.  `None` means the request assumes no
derivation at all, never a default zero derivation.  The same target may be
differentiated with another derivation in another request; the request is the
single authority for the chosen one.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from typing import TYPE_CHECKING, Any

from cas.algebra.parents import Parent
from cas.algebra.protocols import CoefficientRing, GeneratorRing
from cas.foundation.ids import SymbolId
from cas.language import sorts as S
from cas.language.problems import (
    InterpretationRequirement,
    ParameterMode,
    ValueDomain,
    VariableRoles,
    shared_variable_sort,
    value_domain_of_sort,
)
from cas.semantics.differential import DifferentialStructure

if TYPE_CHECKING:
    from cas.language.problems import Role


class Interpretation(StrEnum):
    """How the requested value is meant."""

    FORMAL = "formal"
    PARAMETER_FAMILY = "parameter_family"
    EMBEDDED = "embedded"


_INTERPRETATION_REQUIREMENTS = {
    Interpretation.FORMAL: InterpretationRequirement.FORMAL,
    Interpretation.PARAMETER_FAMILY: (
        InterpretationRequirement.PARAMETER_FAMILY
    ),
    Interpretation.EMBEDDED: InterpretationRequirement.EMBEDDED,
}


@dataclass(frozen=True, slots=True, eq=False)
class AlgebraRequest:
    """One task's algebra view.

    `coefficient` is the structure the numbers live in, `parameter_ring` is the
    optional structure generated by formal parameters, and `roles` fixes the
    target and parameter roles.  The three roles are fixed once and shared with
    the matching problem.  The role set is world-scoped: its `SymbolId` values
    are local to `roles.world`, never a global integer identity.  A request with
    an unbound role world is refused, and the bridges refuse a request whose
    world differs from the source expression's meaning world.

    `differential` is the request-local derivation.  It is optional because not
    every algebra request differentiates; `None` means no derivation is
    assumed, never a zero derivation.  When present, this exact structure is
    the single authority a differentiation view may use.

    `coefficient_domain` is the language-level coefficient range this request
    was assembled for.  It is declared data, not inferred by sniffing the
    parent: a Q-based assembly states `RATIONAL`, a Z-based one `INTEGER`.  The
    allowed value domain is derived from the target sort, or from the single
    shared generator sort in generator mode, through the same language mapping
    `ProblemSpec` uses, so a fixed problem and its resolved request cannot
    disagree about either side of the domain binding.

    A request has exactly one of two role shapes in this slice.  Target mode
    fixes one target symbol and its sort; generator mode fixes an ordered,
    nonempty generator tuple with identical dense sorts and binds no target.
    Generator mode is the multivariate shape: the request's `target` property
    has no value there and raises instead of inventing a symbol.  Formal
    parameters remain a target-mode feature; generator mode refuses a parameter
    ring, declared parameters and the parameter-family interpretation.
    """

    coefficient: Parent[Any]
    coefficient_domain: ValueDomain
    parameter_ring: Parent[Any] | None
    roles: VariableRoles
    interpretation: Interpretation
    differential: DifferentialStructure[Any] | None = None

    def __post_init__(self) -> None:
        if not isinstance(self.coefficient, Parent):
            raise TypeError("an algebra request needs a coefficient parent")
        if not isinstance(self.coefficient_domain, ValueDomain):
            raise TypeError(
                "an algebra request needs a ValueDomain coefficient domain"
            )
        if self.parameter_ring is not None and not isinstance(
            self.parameter_ring, Parent
        ):
            raise TypeError("an algebra request needs a parent parameter ring")
        if not isinstance(self.roles, VariableRoles):
            raise TypeError("an algebra request needs fixed variable roles")
        if self.roles.world is None:
            raise ValueError(
                "an algebra request needs a world-scoped role set"
            )
        if self.roles.target is None:
            if not self.roles.variables:
                raise ValueError(
                    "an algebra request needs a target role or generator roles"
                )
            if self.roles.parameters or self.parameter_ring is not None:
                raise ValueError(
                    "a generator algebra request cannot declare parameters"
                )
            shared_variable_sort(self.roles)
            if self.interpretation is Interpretation.PARAMETER_FAMILY:
                raise ValueError(
                    "a generator algebra request cannot use a "
                    "parameter-family interpretation"
                )
        else:
            target_sort = self.roles.target_sort
            if target_sort is None:
                raise ValueError("an algebra request needs a target sort")
            value_domain_of_sort(target_sort)
        if self.roles.parameters and (
            len(self.roles.parameter_sorts) != len(self.roles.parameters)
        ):
            raise ValueError(
                "an algebra request needs matching parameter role sorts"
            )
        if not isinstance(self.interpretation, Interpretation):
            raise TypeError("an algebra request needs an interpretation")
        if self.differential is not None and not isinstance(
            self.differential, DifferentialStructure
        ):
            raise TypeError(
                "an algebra request differential must be a "
                "DifferentialStructure"
            )
        parameters = self.roles.parameters
        if self.parameter_ring is None and parameters:
            raise ValueError("declared parameters need a parameter ring")
        if self.parameter_ring is not None and not parameters:
            raise ValueError("a parameter ring needs at least one parameter")
        if self.parameter_ring is not None:
            ring = self.parameter_ring.ring
            if not isinstance(ring, GeneratorRing):
                raise ValueError(
                    "the parameter ring must expose its generators"
                )
            if tuple(ring.generators) != parameters:
                raise ValueError(
                    "the parameter ring generators must be the declared "
                    "parameters"
                )
            if not isinstance(ring, CoefficientRing):
                raise ValueError(
                    "the parameter ring must expose its coefficient structure"
                )
            if ring.coefficients is not self.coefficient.ring:
                raise ValueError(
                    "the parameter ring must be built over the coefficient "
                    "parent"
                )
            if self.parameter_ring.spec.base != self.coefficient.spec:
                raise ValueError(
                    "the parameter ring must extend the coefficient parent"
                )

    @property
    def target(self) -> SymbolId:
        """The target role fixed by this request.

        A generator-mode request has no single target; asking for one is a
        caller error and raises instead of returning an arbitrary generator.
        """
        target = self.roles.target
        if target is None:
            raise ValueError(
                "a generator-mode algebra request has no target role"
            )
        return target

    @property
    def parameters(self) -> tuple[SymbolId, ...]:
        """The parameter roles fixed by this request."""
        return self.roles.parameters

    @property
    def variables(self) -> tuple[SymbolId, ...]:
        """The ordered generator roles fixed by this request."""
        return self.roles.variables

    @property
    def variable_sorts(self) -> tuple[S.Sort, ...]:
        """The generator sorts fixed by this request."""
        return self.roles.variable_sorts

    @property
    def parameter_mode(self) -> ParameterMode:
        """The parameter promise fixed by this request."""
        return self.roles.parameter_mode

    @property
    def interpretation_requirement(self) -> InterpretationRequirement:
        """The language-owned interpretation this request requires."""
        return _INTERPRETATION_REQUIREMENTS[self.interpretation]

    @property
    def value_domain(self) -> ValueDomain:
        """The allowed value domain derived from the role sorts."""
        target_sort = self.roles.target_sort
        if target_sort is not None:
            return value_domain_of_sort(target_sort)
        if self.roles.variables:
            return value_domain_of_sort(shared_variable_sort(self.roles))
        raise ValueError(
            "an algebra request has no target or generator sort"
        )

    def role_of(self, symbol_id: SymbolId) -> "Role | None":
        """The role of `symbol_id` in this request, if it has one."""
        return self.roles.role_of(symbol_id)


__all__ = ["AlgebraRequest", "Interpretation"]
