E = TypeVar("E")

_BUDGET_MISSING = frozenset({"buchberger_budget"})
_SEAL = object()
_UNSEALED = object()


class BuchbergerBudgetError(RuntimeError):
    """The Buchberger budget was exhausted before a complete basis existed.

    This is resource control, not a statement about the ideal.  No partial
    basis may be returned or published as complete.  ``phase`` records the
    work item that exhausted the budget.
    """

    def __init__(
        self,
        detail: str,
        *,
        used: int,
        budget: int,
        phase: str,
    ) -> None:
        super().__init__(detail)
        self.detail = detail
        self.used = used
        self.budget = budget
        self.phase = phase
        self.missing = _BUDGET_MISSING


@dataclass(frozen=True, slots=True)
class GroebnerStatistics:
    """Work performed by one Buchberger search and its final interreduction.

    Record validation is a separate structural check and is not counted.
    """

    pairs: int
    reductions: int


@dataclass(frozen=True, slots=True, eq=False)
class GroebnerBasis(Generic[E]):
    """A reduced Groebner basis with cofactors and its original generators.

    The record is immutable and sealed: only ``buchberger`` issues it.  Direct
    construction or ``dataclasses.replace`` is rejected, because a caller could
    otherwise present a merely reduced basis as a Groebner basis and obtain
    wrong answers from ``ideal_membership``/``ideal_equal``.  ``basis``
    contains monic, nonzero, interreduced polynomials; ``cofactors[i]`` gives
    ``basis[i] == sum_j cofactors[i][j] * original_generators[j]``.  The
    constructor validates the structural reduced-basis conditions, the
    cofactor identities, ring/order ownership, and that every original
    generator reduces to zero modulo the basis.  The Buchberger criterion is
    deliberately not rechecked here: the independent checker of the next batch
    is the trust boundary, and this record is the search-side proposal.

    Python equality is not mathematical equality (the polynomial type also
    uses identity-based equality).  Compare elements with ``ring.equal`` and
    ideals with ``ideal_equal``.
    """

    ring: PolynomialRing[E]
    order: MonomialOrder
    original_generators: tuple[Polynomial[E], ...]
    basis: tuple[Polynomial[E], ...]
    cofactors: tuple[tuple[Polynomial[E], ...], ...]
    statistics: GroebnerStatistics
    _seal: object = field(
        init=False, default=_UNSEALED, repr=False, compare=False
    )

    def __post_init__(self) -> None:
        if self._seal is not _SEAL:
            raise ValueError(
                "a GroebnerBasis is issued only by buchberger"
            )
        ring = self.ring
        _require_field(ring, "a Groebner basis")
        if self.order != ring.monomial_order:
            raise ValueError("the Groebner basis order is not the ring's order")
        for generator in self.original_generators:
            _require_owned(ring, generator, "a Groebner basis")
        if len(self.cofactors) != len(self.basis):
            raise ValueError("every basis element needs one cofactor row")
        for element, cofactors in zip(self.basis, self.cofactors):
            _require_owned(ring, element, "a Groebner basis")
            if len(cofactors) != len(self.original_generators):
                raise ValueError(
                    "a cofactor row must align with the original generators"
                )
            for cofactor in cofactors:
                _require_owned(ring, cofactor, "a Groebner basis")
        for element in self.basis:
            if element.is_zero():
                raise ValueError("a Groebner basis element must be nonzero")
            leading = leading_coefficient(ring, element)
            if not ring.coefficients.is_one(leading):
                raise ValueError("a Groebner basis element must be monic")

        for index, element in enumerate(self.basis):
            for exponents, _ in element.terms:
                for other_index, other in enumerate(self.basis):
                    if index == other_index:
                        continue
                    other_leading = leading_monomial(ring, other)
                    if _monomial_divides(other_leading, exponents):
                        raise ValueError(
                            "a Groebner basis element is not reduced by the others"
                        )

        for element, cofactors in zip(self.basis, self.cofactors):
            combination = ring.sum(
                ring.mul(cofactor, generator)
                for cofactor, generator in zip(
                    cofactors, self.original_generators
                )
            )
            if not ring.equal(combination, element):
                raise ValueError(
                    "the cofactor identity does not express the basis element"
                )

        for generator in self.original_generators:
            if not normal_form(ring, generator, self.basis).is_zero():
                raise ValueError(
                    "an original generator is not in the ideal of the basis"
                )

    @classmethod
    def _issue(
        cls,
        ring: PolynomialRing[E],
        order: MonomialOrder,
        original_generators: tuple[Polynomial[E], ...],
        basis: tuple[Polynomial[E], ...],
        cofactors: tuple[tuple[Polynomial[E], ...], ...],
        statistics: GroebnerStatistics,
    ) -> GroebnerBasis[E]:
        """Issue a sealed record; the only caller is ``buchberger``."""
        record: GroebnerBasis[E] = object.__new__(cls)
        object.__setattr__(record, "ring", ring)
        object.__setattr__(record, "order", order)
        object.__setattr__(record, "original_generators", original_generators)
        object.__setattr__(record, "basis", basis)
        object.__setattr__(record, "cofactors", cofactors)
        object.__setattr__(record, "statistics", statistics)
        object.__setattr__(record, "_seal", _SEAL)
        record.__post_init__()
        return record


def buchberger(
    ring: PolynomialRing[E],
    generators: Iterable[Polynomial[E]],
    *,
    budget: int,
) -> GroebnerBasis[E]:
    """Compute a reduced Groebner basis with cofactors over a field.

    The pair queue is processed in a deterministic order.  Every returned
    element is monic and the basis is interreduced and sorted by leading
    monomial.  Cofactors express each basis element in terms of the original
    generator sequence exactly.

    ``budget`` counts critical pairs and leading-term reductions.  Exhaustion
    raises ``BuchbergerBudgetError``; a partial basis is never returned.
    """
    _require_field(ring, "Buchberger's algorithm")
    if isinstance(budget, bool) or not isinstance(budget, int):
        raise TypeError(
            "the Buchberger budget must be an int (bool is not accepted)"
        )
    if budget < 0:
        raise ValueError("the Buchberger budget must be nonnegative")
    original = tuple(generators)
    for generator in original:
        _require_owned(ring, generator, "Buchberger's algorithm")

    work_budget = _WorkBudget(budget)
    zero = ring.zero()
    one = ring.one()
    working: list[_Element[E]] = []
    for index, generator in enumerate(original):
        if generator.is_zero():
            continue
        cofactors = tuple(
            one if slot == index else zero for slot in range(len(original))
        )
        element = _monic_element(ring, _Element(generator, cofactors))
        if not any(
            ring.equal(existing.polynomial, element.polynomial)
            for existing in working
        ):
            working.append(element)

    queue: deque[tuple[int, int]] = deque(
        (left, right)
        for left in range(len(working))
        for right in range(left + 1, len(working))
    )
    pairs = 0
    reductions = 0
    while queue:
        left_index, right_index = queue.popleft()
        work_budget.spend("critical pair")
        pairs += 1
        value, cofactors = _s_pair(
            ring, working[left_index], working[right_index]
        )
        remainder, remainder_cofactors, spent = _reduce_with_cofactors(
            ring, value, cofactors, working, work_budget
        )
        reductions += spent
        if remainder.is_zero():
            continue
        element = _monic_element(
            ring, _Element(remainder, remainder_cofactors)
        )
        new_index = len(working)
        working.append(element)
        for index in range(new_index):
            queue.append((index, new_index))

    reduced, spent = _reduce_basis(ring, working, work_budget)
    reductions += spent
    return GroebnerBasis._issue(
        ring=ring,
        order=ring.monomial_order,
        original_generators=original,
        basis=tuple(element.polynomial for element in reduced),
        cofactors=tuple(element.cofactors for element in reduced),
        statistics=GroebnerStatistics(pairs=pairs, reductions=reductions),
    )


def ideal_membership(
    basis: GroebnerBasis[E],
    polynomial: Polynomial[E],
) -> bool:
    """Whether ``polynomial`` lies in the ideal represented by ``basis``.

    This helper is defined only on a record issued by ``buchberger``.  The
    sealed record guarantees that the search-side construction used the
    Buchberger algorithm; the independent checker of the next batch still
    verifies the Buchberger criterion before any publication.  A merely
    reduced basis that is not a Groebner basis does not define a correct ideal
    normal form, which is why direct record construction is rejected.
    """
    _require_owned(basis.ring, polynomial, "ideal membership")
    return normal_form(basis.ring, polynomial, basis.basis).is_zero()


def ideal_equal(left: GroebnerBasis[E], right: GroebnerBasis[E]) -> bool:
    """Whether two Groebner bases describe the same ideal in the same ring.

    Both records must have been issued by ``buchberger`` and belong to the same
    ring object and order.  Equality is decided by mutual ideal inclusion; for
    two actual Groebner bases this is exact and does not depend on the chosen
    generator list.  The independent checker remains the trust boundary for the
    Buchberger criterion.
    """
    if left.ring is not right.ring:
        raise ValueError("ideals must live in the same polynomial ring")
    if left.order != right.order:
        raise ValueError("ideals must use the same monomial order")
    return all(
        ideal_membership(right, element) for element in left.basis
    ) and all(ideal_membership(left, element) for element in right.basis)


@dataclass(frozen=True, slots=True)
class _Element(Generic[E]):
    polynomial: Polynomial[E]
    cofactors: tuple[Polynomial[E], ...]


@dataclass(slots=True)
class _WorkBudget:
    limit: int
    used: int = 0

    def spend(self, phase: str) -> None:
        self.used += 1
        if self.used > self.limit:
            raise BuchbergerBudgetError(
                f"Buchberger budget {self.limit} exhausted during {phase}",
                used=self.used,
                budget=self.limit,
                phase=phase,
            )


def _monic_element(
    ring: PolynomialRing[E],
    element: _Element[E],
) -> _Element[E]:
    coefficients = _require_field(ring, "monic normalisation")
    leading = leading_coefficient(ring, element.polynomial)
    if coefficients.is_one(leading):
        return element
    scale = coefficients.inv(leading)
    multiplier = ring.constant(scale)
    return _Element(
        ring.mul(multiplier, element.polynomial),
        tuple(
            ring.mul(multiplier, cofactor)
            for cofactor in element.cofactors
        ),
    )


def _s_pair(
    ring: PolynomialRing[E],
    left: _Element[E],
    right: _Element[E],
) -> tuple[Polynomial[E], tuple[Polynomial[E], ...]]:
    value, left_multiplier, right_multiplier = s_polynomial_parts(
        ring, left.polynomial, right.polynomial
    )
    cofactors = tuple(
        ring.sub(
            ring.mul(left_multiplier, left_cofactor),
            ring.mul(right_multiplier, right_cofactor),
        )
        for left_cofactor, right_cofactor in zip(
            left.cofactors, right.cofactors
        )
    )
    return value, cofactors


def _reduce_with_cofactors(
    ring: PolynomialRing[E],
    value: Polynomial[E],
    cofactors: tuple[Polynomial[E], ...],
    basis: list[_Element[E]],
    budget: _WorkBudget,
) -> tuple[Polynomial[E], tuple[Polynomial[E], ...], int]:
    division, reductions = _divide(
        ring,
        value,
        tuple(element.polynomial for element in basis),
        spend=budget.spend,
    )
    reduced_cofactors = list(cofactors)
    for quotient, element in zip(division.quotients, basis):
        if quotient.is_zero():
            continue
        for index, element_cofactor in enumerate(element.cofactors):
            reduced_cofactors[index] = ring.sub(
                reduced_cofactors[index],
                ring.mul(quotient, element_cofactor),
            )
    return division.remainder, tuple(reduced_cofactors), reductions


def _reduce_basis(
    ring: PolynomialRing[E],
    basis: list[_Element[E]],
    budget: _WorkBudget,
) -> tuple[tuple[_Element[E], ...], int]:
    current = list(basis)
    reductions = 0
    changed = True
    while changed:
        changed = False
        for index in range(len(current)):
            others = current[:index] + current[index + 1 :]
            value, cofactors, spent = _reduce_with_cofactors(
                ring,
                current[index].polynomial,
                current[index].cofactors,
                others,
                budget,
            )
            reductions += spent
            if value.is_zero():
                del current[index]
                changed = True
                break
            element = _monic_element(ring, _Element(value, cofactors))
            if not ring.equal(element.polynomial, current[index].polynomial):
                current[index] = element
                changed = True
                break
    current.sort(
        key=lambda element: ring.monomial_order.key(
            leading_monomial(ring, element.polynomial)
        )
    )
    return tuple(current), reductions


