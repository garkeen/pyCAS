"""Buchberger's algorithm and the sealed reduced-basis record over a field.

This module owns the search side of the G0 algebra core: Buchberger's
algorithm, a reduced monic interreduced basis, and cofactor representations of
every basis element in terms of the original generators.  The pure primitives
it consumes -- multivariate division with quotients, leading-term helpers and
S-polynomials -- live in ``cas.algebra.multivariate``, so the independent
checker of the next batch can import them without importing this search
module.  This is a low-level API over ``PolynomialRing[E]`` and does not import
the syntax, semantics, workflow, kernel or ``math`` layers.

Scope boundary
--------------

This batch is not an end-to-end G0 capability.  The generator-mode request and
view foundation exists (``Role.GENERATOR``, ``VariableRoles.variables``/
``variable_sorts``, generator-mode ``ProblemSpec``/``AlgebraRequest`` and
``MultivariatePolynomialBridge``), but there is still no multivariate result
model, no registered ``groebner_basis`` operation, no independent checker, no
bootstrap registration, no workflow/REPL support and no default-frame ``y``.
The next batch has to provide that S1 wiring and an independent checker that
consumes the cofactors recorded here.  In particular, this module never
publishes a judgment.

Buchberger and cofactors
------------------------

``buchberger`` runs the pair-queue form of Buchberger's algorithm.  It
normalises generators to monic polynomials, removes exact duplicates from the
working set, processes all critical pairs in a deterministic order, reduces
each S-polynomial by the current basis, and adds every nonzero remainder.  The
finished basis is interreduced: every element is monic, nonzero, and no
monomial of one element is divisible by the leading monomial of another.
The returned basis is sorted by leading monomial under the ring order, which
is a deterministic presentation of the unique reduced basis for that order.

For every final basis element ``g`` the record carries polynomial cofactors
``c_i`` over the same polynomial ring with

    g = sum_i c_i * f_i

where the ``f_i`` are the original generators in the supplied order.  The
cofactors survive monic scaling, S-polynomial combinations, normal-form
reductions and final interreduction.  They are the data an independent checker
will use to verify that every new generator lies in the original ideal; the
Buchberger criterion itself is checked by that later checker, not here.
``GroebnerBasis`` is sealed: only ``buchberger`` issues a record, so callers
cannot pass off an arbitrary reduced basis as a Groebner basis to
``ideal_membership``/``ideal_equal``.  Direct construction and
``dataclasses.replace`` are rejected.

Zero generators are excluded from the working set but retained in
``original_generators`` (with zero cofactor columns), so the recorded identity
is with respect to the caller's exact input sequence.  Exact duplicate or
scalar-multiple generators are normalised to the same monic polynomial and
only the first working copy is retained; the caller's sequence is still
recorded.  The zero ideal is represented by an empty basis.

Termination and budget
----------------------

The coefficient structure is a field, so the ideal generated by finitely many
polynomials has a finite Groebner basis (Hilbert's basis theorem / ascending
chain condition in ``K[x_1, ..., x_n]``).  Division terminates because every
reduction strictly decreases the leading monomial in a well-order.  The pair
queue is finite: each new basis element is appended once and pairs are never
generated for removed elements (only the final interreduction removes
elements, after all pairs are processed).

``budget`` counts critical pairs processed and leading-term reductions
(including final interreduction).  It is resource control only.  Exhaustion
raises ``BuchbergerBudgetError`` with the phase and the attempted amount; no
partial basis is returned.  A budget never changes the mathematical truth of a
completed answer.

Preconditions and refusals
--------------------------

- The coefficient structure must implement ``Field[E]``.  Buchberger's
  algorithm works over any field, including positive characteristic; no
  characteristic-zero or ordered-field precondition is imposed here.
- Every polynomial must belong to the supplied ring.  Mixed rings are
  rejected before any arithmetic.
- Zero divisors and zero S-polynomial arguments are refused explicitly; they
  have no leading monomial.  Zero generators in ``buchberger`` are handled as
  described above.
- The empty divisor list is allowed by division: it returns no quotients and
  leaves the input as the remainder.  The empty generator list defines the
  zero ideal and returns an empty basis.

References
----------

B. Buchberger, *Ein Algorithmus zum Auffinden der Basiselemente des
Restklassenrings nach einem nulldimensionalen Polynomideal* (doctoral thesis,
1965), and "Ein algorithmisches Kriterium für die Lösbarkeit eines
algebraischen Gleichungssystems", *Aequationes Mathematicae* 4 (1970),
374-383, for the algorithm and the S-polynomial criterion.  D. Cox, J. Little
and D. O'Shea, *Ideals, Varieties, and Algorithms*, 4th ed., Chapter 2
(division algorithm, S-polynomials, Buchberger's algorithm, reduced bases) for
the textbook treatment and the uniqueness of the reduced Groebner basis.
Geddes, Czapor and Labahn, *Algorithms for Computer Algebra*, Chapter 7, for
the polynomial-algebra background.  Reference implementations: FriCAS
``src/algebra/gb.spad`` (``GroebnerPackage``) and ``src/algebra/gbintern.spad``
(internal normal-form reductions); Maxima ``share/algebra/grob1.lisp`` and
``share/contrib/Grobner/grobner.lisp``.  These implementations are evidence
for algorithm structure, not replacements for the proofs above.
"""

from __future__ import annotations

from collections import deque
from dataclasses import dataclass, field
